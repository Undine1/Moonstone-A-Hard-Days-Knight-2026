#!/usr/bin/env python3
"""Encode a boot-splash PNG into recomp/src/splash_image.h.

The splash fills the 320x256 logical render area (5:4). It is embedded at the
default-scale window resolution (960x768) so it renders crisp 1:1. Raw RGB24
pixels are uploaded directly to SDL, without a decoder or temporary allocation.
This deliberately trades executable size for a simpler boot path, preserving
every pixel of the previous lossless QOI representation.

Usage:  python recomp/tools/splash_to_h.py <splash.png>
"""
import os, sys
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else None
if not SRC or not os.path.exists(SRC):
    sys.exit("usage: splash_to_h.py <splash.png>")

W, H = 960, 768
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "splash_image.h")

im = Image.open(SRC).convert("RGB").resize((W, H), Image.LANCZOS)
rgb = im.tobytes()
body = "\n".join("    " + ",".join(f"0x{byte:02x}" for byte in rgb[i:i+24]) + ","
                 for i in range(0, len(rgb), 24))

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(f"""#ifndef SPLASH_IMAGE_INCLUDED
#define SPLASH_IMAGE_INCLUDED
#include <stdint.h>
/* Boot splash -- GENERATED by recomp/tools/splash_to_h.py from an original PNG.
 * {W}x{H}, uncompressed RGB24 ({len(rgb)} bytes, no decoder).
 * Uploaded once at boot; see run_sdl in moon.c. */
#define SPLASH_W {W}
#define SPLASH_H {H}
static const uint8_t splash_rgb[] = {{
{body}
}};
#endif
""")
print(f"wrote {OUT}: {W}x{H}  RGB24={len(rgb)}B")
